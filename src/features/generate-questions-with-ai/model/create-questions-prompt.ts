import { TGenerateQuestions } from "../model/types";

export function createQuestionsPrompt({
  courseName,
  themeName,
  count,
  instructions,
  existingQuestions,
}: TGenerateQuestions) {
  return `
Ты — опытный технический интервьюер и преподаватель
в сфере разработки программного обеспечения.

Твоя задача — составить список вопросов для учебного курса "${courseName}" по теме "${themeName}".

При выборе вопросов ориентируйся в первую очередь на вопросы ,
которые наиболее часто встречаются на технических собеседованиях
по "${courseName}" и теме "${themeName}".

Требования:

1. Выбирай практические и востребованные вопросы.
2. Каждый вопрос должен непосредственно относиться к теме "${themeName}".
3. Вопросы не должны дублировать друг друга по смыслу.
4. Не создавай вопросы, которые уже существуют в курсе.
5. Для каждого вопроса создай ровно три варианта ответа.
6. В "answer_1" всегда должен находиться правильный ответ.
7. В "answer_2" и "answer_3" должны находиться неправильные ответы.
8. Неправильные ответы должны быть правдоподобными и похожими
   по стилю и уровню детализации на правильный ответ,
   но при этом быть однозначно неверными.
9. Все три варианта ответа должны быть сопоставимы по длине,
   стилю и уровню детализации.

Уже существующие вопросы:
${existingQuestions?.length ? existingQuestions.join(", ") : "Нет"}

Дополнительные пожелания пользователя:
${instructions.trim() || "Нет дополнительных пожеланий."}

Верни ровно ${count} элементов.

Верни результат строго в виде валидного JSON-массива объектов следующей структуры:

[
  {
    "question": "",
    "answer_1": "",
    "answer_2": "",
    "answer_3": ""
  }
]

Не добавляй Markdown, пояснения, комментарии, вступительный текст
или любой другой текст вне JSON-массива.
`;
}
// При выборе тем используй поиск Google, чтобы определить,
// какие темы по "${courseName}" наиболее часто встречаются
// на технических собеседованиях.

// На основании найденной информации выбери ${count}
// наиболее востребованных тем.
