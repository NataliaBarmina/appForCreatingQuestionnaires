export function createThemesPrompt({
  courseName,
  count,
  instructions,
  existingThemes,
}: {
  courseName: string;
  count: number;
  instructions: string;
  existingThemes?: string[];
}) {
  return `
Ты — опытный технический интервьюер и преподаватель
в сфере разработки программного обеспечения.

Твоя задача — составить список тем для учебного курса "${courseName}".

При выборе тем ориентируйся в первую очередь на темы,
которые наиболее часто встречаются на технических собеседованиях
по "${courseName}".

Требования:
1. Выбирай практические и востребованные темы.
2. Темы должны относиться непосредственно к курсу "${courseName}".
3. Не создавай слишком общие темы.
4. Темы не должны дублировать друг друга.
5. Не создавай темы, которые уже существуют в курсе.

Уже существующие темы:
${existingThemes?.length ? existingThemes.join(", ") : "Нет"}

Дополнительные пожелания пользователя:
${instructions.trim() || "Нет дополнительных пожеланий."}

Верни результат строго в виде JSON-массива строк:

[
  "Название темы 1",
  "Название темы 2",
  "Название темы 3"
]

Верни ровно ${count} элементов.
Не добавляй пояснений, Markdown, комментариев или другого текста вне массива.
`;
}
// При выборе тем используй поиск Google, чтобы определить,
// какие темы по "${courseName}" наиболее часто встречаются
// на технических собеседованиях.

// На основании найденной информации выбери ${count}
// наиболее востребованных тем.
